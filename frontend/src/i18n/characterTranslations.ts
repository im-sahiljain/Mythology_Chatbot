/**
 * Helper function to retrieve localized character info based on language
 */
export function getLocalizedCharacter(
  character: { name: string; role?: string; archetype?: string; subtitle?: string; quote?: string },
  language: string = "en"
): { name: string; role: string; subtitle: string; quote: string } {
  const rawLang = (language || "en").toLowerCase();
  const matchedKey = CHARACTER_TRANSLATIONS[rawLang]
    ? rawLang
    : CHARACTER_TRANSLATIONS[rawLang.slice(0, 2)]
    ? rawLang.slice(0, 2)
    : "en";
  const transMap = CHARACTER_TRANSLATIONS[matchedKey] || CHARACTER_TRANSLATIONS["en"];
  const originalName = character.name;
  const fallbackRole = character.role || character.archetype || "";

  if (transMap && transMap[originalName]) {
    const t = transMap[originalName];
    return {
      name: t.name || originalName,
      role: t.role || fallbackRole,
      subtitle: t.subtitle || character.subtitle || "",
      quote: t.quote || character.quote || "",
    };
  }

  return {
    name: character.name,
    role: fallbackRole,
    subtitle: character.subtitle || "",
    quote: character.quote || "",
  };
}

